import { SpriteFrame, SpriteRenderer, UITransform } from '../../cocos/2d';
import { Texture2D, Material, EffectAsset } from '../../cocos/asset/assets';
import { Color, Rect, Vec3, Vec4, isValid } from '../../cocos/core';
import { CCObject } from '../../cocos/core/data/object';
import { AttributeName, DescriptorSet } from '../../cocos/gfx';
import { Node } from '../../cocos/scene-graph/node';
import { Scene, director } from '../../exports/base';
import { MaterialInstance } from '../../cocos/render-scene/core/material-instance';
import { ModelLocalBindings } from '../../cocos/rendering/define';
import { deserialize } from '../../cocos/serialization/deserialize';

// Object/geometry regressions using Empty GFX. Actual Web/Native rendering is verified separately.
describe('SpriteRenderer resources and lifecycle', () => {
    let scene: Scene;
    let frames: SpriteFrame[];
    let textures: Texture2D[];
    let materials: Material[];

    beforeAll(() => {
        // Generated by the Cocos Effect compiler from builtin-sprite-renderer.effect and current engine chunks.
        // This exercises real reflected material parameters, not GPU output.
        const effect = Object.assign(new EffectAsset(), require('../fixtures/sprite-renderer-effect.json'));
        effect.onLoaded();
    });

    function material (): Material {
        const result = new Material();
        result.initialize({ effectName: 'builtin-sprite-renderer' });
        materials.push(result);
        return result;
    }

    function texture (size = 256): Texture2D {
        const result = new Texture2D();
        result.reset({ width: size, height: size });
        textures.push(result);
        return result;
    }

    function frame (): SpriteFrame {
        const result = new SpriteFrame();
        result.texture = texture();
        result.rect = new Rect(16, 32, 100, 60);
        frames.push(result);
        return result;
    }

    function renderer (active = true): SpriteRenderer {
        const node = new Node('World sprite');
        node.active = active;
        scene.addChild(node);
        return node.addComponent(SpriteRenderer);
    }

    beforeEach(() => {
        frames = [];
        textures = [];
        materials = [];
        scene = new Scene('SpriteRenderer regression');
        director.runSceneImmediate(scene);
    });

    afterEach(() => {
        scene.destroy();
        CCObject._deferredDestroy();
        frames.forEach((asset) => { if (isValid(asset, true)) asset.destroy(); });
        textures.forEach((asset) => { if (isValid(asset, true)) asset.destroy(); });
        materials.forEach((asset) => { if (isValid(asset, true)) asset.destroy(); });
        CCObject._deferredDestroy();
        jest.restoreAllMocks();
    });

    test('shares standard geometry without modifying source vertices or requiring UITransform', () => {
        const asset = frame();
        const first = renderer();
        const second = renderer();
        const serialized = asset._serialize(null);
        first.spriteFrame = second.spriteFrame = asset;
        expect(asset.vertices).toBeNull();
        expect(asset._serialize(null)).toEqual(serialized);
        expect(first.node.getComponent(UITransform)).toBeNull();
        expect(first.model).not.toBe(second.model);
        expect(first.model!.subModels[0].subMesh).toBe(second.model!.subModels[0].subMesh);
        expect(scene.renderScene!.models).toContain(first.model);
        const positions = asset.mesh!.readAttribute(0, AttributeName.ATTR_POSITION)!;
        expect(positions[0]).toBeCloseTo(-0.5);
        first.node.setPosition(2, 3, 5);
        first.model!.updateTransform(1);
        expect(first.model!.worldBounds!.center).toEqual(new Vec3(2, 3, 5));
    });

    test('does not allocate world data for UI-only frames or never-enabled components', () => {
        const asset = frame();
        const keys = Object.keys(asset);
        asset.rect = new Rect(4, 8, 20, 30);
        asset.flipUVX = true;
        expect(Object.keys(asset)).toEqual(keys);
        const source = asset.texture;
        const references = source.refCount;
        asset._setDynamicAtlasFrame({ texture: texture(1024), x: 400, y: 500 });
        expect(asset._getSourceTexture()).toBe(source);
        asset._resetDynamicAtlasFrame();
        expect(Object.keys(asset)).toEqual(keys);
        expect(source.refCount).toBe(references);
        expect(asset.hasEventListener('mesh_changed')).toBe(false);
        const component = renderer(false);
        component.spriteFrame = asset;
        component.onRestore();
        expect(component.model).toBeNull();
        expect(asset.mesh).toBeNull();
        expect(asset.vertices).toBeNull();
        expect(Object.keys(asset)).toEqual(keys);
        component.node.active = true;
        expect(component.model).not.toBeNull();
    });

    test('clearing content stops submission and releases the last derived mesh', () => {
        const component = renderer();
        const asset = frame();
        component.spriteFrame = asset;
        const model = component.model!;
        const mesh = asset.mesh!;
        component.spriteFrame = null;
        expect(scene.renderScene!.models).not.toContain(model);
        expect(component.model).toBeNull();
        expect(asset.mesh).toBeNull();
        expect(isValid(mesh, true)).toBe(false);
    });

    test('applies priority and visibility on delayed creation, changes and rebind', () => {
        const component = renderer();
        component.priority = 54321;
        component.visibility = 2;
        component.spriteFrame = frame();
        expect(component.model!.priority).toBe(54321);
        expect(component.model!.visFlags).toBe(2);
        component.visibility = 4;
        expect(component.model!.visFlags).toBe(4);
        component.spriteFrame!.rect = new Rect(0, 0, 40, 20);
        expect(component.model!.priority).toBe(54321);
        expect(component.model!.visFlags).toBe(4);
        component.spriteFrame = frame();
        expect(component.model!.priority).toBe(54321);
        expect(component.model!.visFlags).toBe(4);
    });

    test.each([false, true])('uses asset UV rotation and flips (rotated=%s)', (rotated) => {
        const asset = frame();
        asset.rotated = rotated;
        const component = renderer();
        component.spriteFrame = asset;
        for (const [x, y] of [[false, false], [true, false], [false, true], [true, true]]) {
            asset.flipUVX = x;
            asset.flipUVY = y;
            const uv = asset.mesh!.readAttribute(0, AttributeName.ATTR_TEX_COORD)!;
            asset.uv.forEach((value, index) => expect(uv[index]).toBeCloseTo(index % 2 ? 1 - value : value));
        }
    });

    test('updates both consumers before destroying replaced geometry', () => {
        const asset = frame();
        const first = renderer();
        const second = renderer();
        first.spriteFrame = second.spriteFrame = asset;
        const oldMesh = asset.mesh!;
        const oldSubMesh = oldMesh.renderingSubMeshes[0];
        const destroy = oldSubMesh.destroy.bind(oldSubMesh);
        const release = jest.spyOn(oldSubMesh, 'destroy').mockImplementation(() => {
            expect(first.model!.subModels[0].subMesh).not.toBe(oldSubMesh);
            expect(second.model!.subModels[0].subMesh).not.toBe(oldSubMesh);
            destroy();
        });
        asset.rect = new Rect(48, 64, 40, 20);
        expect(release).toHaveBeenCalledTimes(1);
        expect(first.model!.subModels[0].subMesh).toBe(second.model!.subModels[0].subMesh);
        expect(first.model!.modelBounds!.halfExtents.x).toBeCloseTo(0.2);
        expect(first.model!.modelBounds!.halfExtents.y).toBeCloseTo(0.1);
    });

    test('UI atlas relocation and reset preserve world geometry and descriptors', () => {
        const asset = frame();
        const component = renderer();
        component.spriteFrame = asset;
        const originalTexture = asset.texture;
        const mesh = asset.mesh!;
        const model = component.model!;
        const subModel = model.subModels[0];
        const rebind = jest.spyOn(subModel.descriptorSet, 'bindTexture');
        const destroy = jest.spyOn(model, 'destroy');
        const originalUV = Array.from(asset.mesh!.readAttribute(0, AttributeName.ATTR_TEX_COORD)!);
        asset._setDynamicAtlasFrame({ texture: texture(1024), x: 400, y: 500 });
        expect(component.model!.subModels[0].subMesh).toBe(asset.mesh!.renderingSubMeshes[0]);
        expect(asset._getSourceTexture()).toBe(originalTexture);
        expect(asset.mesh).toBe(mesh);
        expect(model.subModels[0]).toBe(subModel);
        expect(Array.from(asset.mesh!.readAttribute(0, AttributeName.ATTR_TEX_COORD)!)).toEqual(originalUV);
        asset._resetDynamicAtlasFrame();
        expect(asset.texture).toBe(originalTexture);
        expect(Array.from(asset.mesh!.readAttribute(0, AttributeName.ATTR_TEX_COORD)!)).toEqual(originalUV);
        expect(asset.mesh).toBe(mesh);
        expect(rebind).not.toHaveBeenCalled();
        expect(destroy).not.toHaveBeenCalled();
        asset.texture = texture(512);
        expect(asset.mesh).not.toBe(mesh);
        expect(component.model!.subModels[0].subMesh).toBe(asset.mesh!.renderingSubMeshes[0]);
    });

    test.each([false, true])('first world use of an already-packed frame reads source rotation/flips (rotated=%s)', rotated => {
        const asset = frame();
        asset.rotated = rotated;
        const source = asset.texture;
        const count = source.refCount;
        const atlas = texture(1024);
        for (const [x, y] of [[false, false], [true, false], [false, true], [true, true]]) {
            asset.flipUVX = x;
            asset.flipUVY = y;
            const expected = asset.uv.map((v, i) => i % 2 ? 1 - v : v);
            asset._setDynamicAtlasFrame({ texture: atlas, x: 400, y: 500 });
            const component = renderer();
            const bind = jest.spyOn(DescriptorSet.prototype, 'bindTexture');
            component.spriteFrame = asset;
            expect(bind).toHaveBeenCalledWith(ModelLocalBindings.SAMPLER_SPRITE, source.getGFXTexture());
            const uv = asset.mesh!.readAttribute(0, AttributeName.ATTR_TEX_COORD)!;
            expected.forEach((value, i) => expect(uv[i]).toBeCloseTo(value));
            expect(source.refCount).toBe(count + 1);
            component.enabled = false;
            const mesh = asset.mesh;
            asset._resetDynamicAtlasFrame();
            expect(asset.mesh).toBe(mesh);
            component.enabled = true;
            expect(asset.mesh).toBe(mesh);
            component.spriteFrame = null;
            expect(source.refCount).toBe(count);
            expect(Object.hasOwn(asset, '_meshTexture')).toBe(false);
            bind.mockRestore();
        }
    });

    test('source edits while packed update world data and survive subsequent atlas reset', () => {
        const asset = frame();
        const component = renderer();
        component.spriteFrame = asset;
        const source = asset.texture;
        const originalCount = source.refCount;
        asset._setDynamicAtlasFrame({ texture: texture(1024), x: 400, y: 500 });
        const mesh = asset.mesh;
        asset.rect = new Rect(408, 504, 50, 30); // Coordinates in the public current texture.
        expect(asset.mesh).not.toBe(mesh);
        expect(asset._getSourceTexture()).toBe(source);
        const expected = new SpriteFrame();
        frames.push(expected);
        expected.texture = source;
        expected.rect = new Rect(24, 36, 50, 30);
        expected.flipUVX = asset.flipUVX = true;
        const uv = asset.mesh!.readAttribute(0, AttributeName.ATTR_TEX_COORD)!;
        expected.uv.forEach((value, i) => expect(uv[i]).toBeCloseTo(i % 2 ? 1 - value : value));
        asset._resetDynamicAtlasFrame();
        expect(asset.rect).toEqual(expected.rect);
        asset._setDynamicAtlasFrame({ texture: texture(1024), x: 400, y: 500 });
        const replacement = texture(512);
        asset.texture = replacement;
        expect(asset.original).toBeNull();
        expect(asset._getSourceTexture()).toBe(replacement);
        asset._resetDynamicAtlasFrame();
        expect(asset.texture).toBe(replacement);
        expect(source.refCount).toBe(originalCount - 1);
        component.spriteFrame = null;
        expect(replacement.refCount).toBe(0);
    });

    test('retains disabled resources but discards stale bindings without rebuilding', () => {
        const asset = frame();
        const component = renderer();
        component.spriteFrame = asset;
        const model = component.model;
        const mesh = asset.mesh;
        component.enabled = false;
        expect(scene.renderScene!.models).not.toContain(model);
        expect(asset.mesh).toBe(mesh);
        component.enabled = true;
        expect(component.model).toBe(model);
        expect(asset.mesh).toBe(mesh);
        component.enabled = false;
        asset.rect = new Rect(0, 0, 20, 30);
        expect(asset.mesh).toBeNull();
        expect(component.model).toBeNull();
        component.enabled = true;
        expect(component.model!.modelBounds!.halfExtents.x).toBeCloseTo(0.1);
        expect(component.model!.modelBounds!.halfExtents.y).toBeCloseTo(0.15);
    });

    test('only releases shared geometry when the last world consumer leaves', () => {
        const asset = frame();
        asset.addRef(); // A UI/asset consumer must not keep the derived mesh alive.
        const first = renderer();
        const second = renderer();
        const textureReferences = asset.texture.refCount;
        first.spriteFrame = second.spriteFrame = asset;
        const mesh = asset.mesh;
        expect(asset.texture.refCount).toBe(textureReferences + 1);
        second.enabled = false;
        first.spriteFrame = null;
        expect(asset.mesh).toBe(mesh);
        second.spriteFrame = null;
        expect(asset.mesh).toBeNull();
        expect(asset.texture.refCount).toBe(textureReferences);
        expect(isValid(asset, true)).toBe(true);
        asset.decRef(false);
    });

    test('forced asset destruction detaches consumers before releasing buffers', () => {
        const asset = frame();
        const component = renderer();
        component.spriteFrame = asset;
        const mesh = asset.mesh!;
        const model = component.model;
        asset.destroy();
        expect(component.model).toBeNull();
        expect(scene.renderScene!.models).not.toContain(model);
        expect(isValid(mesh, true)).toBe(false);
        component.enabled = false;
        component.enabled = true;
        expect(component.model).toBeNull();
    });

    test('releases standalone generated geometry when its frame is destroyed', () => {
        const asset = frame();
        asset.ensureMeshData();
        const mesh = asset.mesh!;
        mesh.initialize();
        const destroy = jest.spyOn(mesh.renderingSubMeshes[0], 'destroy');
        asset.destroy();
        expect(destroy).toHaveBeenCalledTimes(1);
        expect(isValid(mesh, true)).toBe(false);
    });

    test('recovers after a zero source rectangle without submitting stale content', () => {
        const asset = frame();
        const component = renderer();
        component.spriteFrame = asset;
        asset.rect = new Rect(0, 0, 0, 20);
        expect(component.model).toBeNull();
        asset.rect = new Rect(0, 0, 40, 20);
        expect(component.model).not.toBeNull();
        expect(component.model!.modelBounds!.halfExtents.x).toBeCloseTo(0.2);
    });

    test('keeps default materials shared and isolates component color from mainColor', () => {
        const shared = material();
        const baseColor = new Color(64, 128, 192, 255);
        shared.setProperty('mainColor', baseColor);
        const asset = frame();
        const first = renderer();
        const second = renderer();
        first.setSharedMaterial(shared, 0);
        second.setSharedMaterial(shared, 0);
        first.spriteFrame = second.spriteFrame = asset;
        const mesh = asset.mesh;
        expect(first.getRenderMaterial(0)).toBe(shared);
        expect(second.getRenderMaterial(0)).toBe(shared);
        first.color = new Color(255, 64, 32, 128);
        expect(first.getRenderMaterial(0)).toBeInstanceOf(MaterialInstance);
        expect(first.getRenderMaterial(0)!.getProperty('spriteColor')).toEqual(first.color);
        expect(first.getRenderMaterial(0)!.getProperty('mainColor')).toEqual(baseColor);
        expect(shared.getProperty('mainColor')).toEqual(baseColor);
        expect(second.getRenderMaterial(0)).toBe(shared);
        expect(asset.mesh).toBe(mesh);
        first.color = Color.WHITE;
        expect(first.getRenderMaterial(0)!.getProperty('spriteColor')).toEqual(Color.WHITE);
    });

    test('legacy inactive color/flip fields do not suddenly change an existing scene', () => {
        const legacy = deserialize({
            __type__: 'cc.SpriteRenderer',
            _color: { __type__: 'cc.Color', r: 255, g: 0, b: 0, a: 128 },
            _flipX: true,
            _flipY: true,
        }) as SpriteRenderer;
        expect(legacy.color).toEqual(Color.WHITE);
        expect(legacy.flipX).toBe(false);
        expect(legacy.flipY).toBe(false);
        const current = deserialize({
            __type__: 'cc.SpriteRenderer',
            _instanceColor: { __type__: 'cc.Color', r: 255, g: 0, b: 0, a: 128 },
            _instanceFlipX: true,
        }) as SpriteRenderer;
        expect(current.color).toEqual(new Color(255, 0, 0, 128));
        expect(current.flipX).toBe(true);
    });

    test('mirrors bounds around the pivot without modifying shared geometry or transforms', () => {
        const component = renderer();
        const asset = frame();
        asset.pivot.set(0.2, 0.7);
        component.setSharedMaterial(material(), 0);
        component.spriteFrame = asset;
        const mesh = asset.mesh!;
        const positions = Array.from(mesh.readAttribute(0, AttributeName.ATTR_POSITION)!);
        const child = new Node('Unflipped child');
        child.setPosition(2, 3, 4);
        component.node.addChild(child);
        const before = component.model!.modelBounds!.center.clone();
        component.flipX = component.flipY = true;
        const after = component.model!.modelBounds!.center;
        expect(after.x).toBeCloseTo(-before.x);
        expect(after.y).toBeCloseTo(-before.y);
        expect(component.getRenderMaterial(0)!.getProperty('spriteFlip')).toEqual(new Vec4(-1, -1, 1, 1));
        expect(asset.mesh).toBe(mesh);
        expect(Array.from(mesh.readAttribute(0, AttributeName.ATTR_POSITION)!)).toEqual(positions);
        expect(component.node.scale).toEqual(Vec3.ONE);
        expect(child.position).toEqual(new Vec3(2, 3, 4));
    });

    test('restores instance parameters after material replacement, rebind and Undo', () => {
        const component = renderer();
        component.setSharedMaterial(material(), 0);
        component.spriteFrame = frame();
        component.color = new Color(32, 64, 128, 192);
        component.flipX = true;
        component.setSharedMaterial(material(), 0);
        component.spriteFrame!.rect = new Rect(0, 0, 20, 30);
        component.onRestore();
        (component.getRenderMaterial(0) as MaterialInstance).recompileShaders({ CC_USE_EMBEDDED_ALPHA: true });
        expect(component.getRenderMaterial(0)!.getProperty('spriteColor')).toEqual(component.color);
        expect(component.getRenderMaterial(0)!.getProperty('spriteFlip')).toEqual(new Vec4(-1, 1, 1, 1));
        expect(scene.renderScene!.models).toContain(component.model);
    });

    test('stores inactive instance changes and applies them when enabled', () => {
        const component = renderer(false);
        component.setSharedMaterial(material(), 0);
        component.spriteFrame = frame();
        component.color = new Color(32, 64, 128, 192);
        component.flipY = true;
        expect(component.getRenderMaterial(0)).toBe(component.sharedMaterial);
        component.node.active = true;
        const instance = component.getRenderMaterial(0)!;
        const upload = jest.spyOn(instance, 'setProperty');
        component.enabled = false;
        component.color = Color.RED;
        component.flipX = true;
        expect(upload).not.toHaveBeenCalled();
        component.enabled = true;
        expect(instance.getProperty('spriteColor')).toEqual(Color.RED);
        expect(instance.getProperty('spriteFlip')).toEqual(new Vec4(-1, -1, 1, 1));
    });

    test('binds separate textures locally without cloning the shared material', () => {
        // EmptyDescriptorSetLayout does not construct binding indices, so observe the real bind calls.
        // Descriptor contents and GPU sampling are covered by the actual graphics validation.
        const bindTexture = jest.spyOn(DescriptorSet.prototype, 'bindTexture');
        const shared = material();
        const first = renderer();
        const second = renderer();
        first.setSharedMaterial(shared, 0);
        second.setSharedMaterial(shared, 0);
        first.spriteFrame = frame();
        second.spriteFrame = frame();
        for (const component of [first, second]) {
            expect(component.getRenderMaterial(0)).toBe(shared);
            expect(bindTexture.mock.calls.some((call, index) => bindTexture.mock.instances[index]
                === component.model!.subModels[0].descriptorSet
                && call[0] === ModelLocalBindings.SAMPLER_SPRITE && call[1] === component.spriteFrame!.getGFXTexture())).toBe(true);
        }
        const replacement = texture(512);
        first.spriteFrame.texture = replacement;
        expect(bindTexture).toHaveBeenLastCalledWith(ModelLocalBindings.SAMPLER_SPRITE, replacement.getGFXTexture());
        expect(second.getRenderMaterial(0)).toBe(shared);
    });

    test('does not mutate or destroy an externally supplied material instance', () => {
        const external = new MaterialInstance({ parent: material() });
        const component = renderer();
        component.setMaterialInstance(external, 0);
        component.spriteFrame = frame();
        const before = external.getProperty('spriteColor');
        component.color = Color.RED;
        expect(component.getRenderMaterial(0)).not.toBe(external);
        expect(external.getProperty('spriteColor')).toEqual(before);
        const owned = component.getRenderMaterial(0)!;
        const release = jest.spyOn(owned, 'destroy');
        const releaseExternal = jest.spyOn(external, 'destroy');
        component.node.destroy();
        CCObject._deferredDestroy();
        expect(release).toHaveBeenCalledTimes(1);
        expect(releaseExternal).not.toHaveBeenCalled();
        external.destroy();
    });

    test('releases its generated material instance when another instance replaces it', () => {
        const component = renderer();
        component.setSharedMaterial(material(), 0);
        component.spriteFrame = frame();
        component.color = Color.RED;
        const previous = component.getRenderMaterial(0)!;
        const release = jest.spyOn(previous, 'destroy');
        const external = new MaterialInstance({ parent: material() });
        component.setMaterialInstance(external, 0);
        expect(release).toHaveBeenCalledTimes(1);
        expect(component.getRenderMaterial(0)!.getProperty('spriteColor')).toEqual(Color.RED);
        expect(component.model!.subModels[0].passes[0]).toBe(component.getRenderMaterial(0)!.passes[0]);
        component.spriteFrame = null;
        external.destroy();
    });
});
