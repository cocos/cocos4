import { SpriteFrame, SpriteFrameEvent, SpriteRenderer, SpriteDrawMode, SpriteTileMode } from '../../cocos/2d';
import { Texture2D, Material, EffectAsset } from '../../cocos/asset/assets';
import { Color, Rect, Vec2, isValid } from '../../cocos/core';
import { CCObject } from '../../cocos/core/data/object';
import { AttributeName } from '../../cocos/gfx';
import { Node } from '../../cocos/scene-graph/node';
import { Scene, director } from '../../exports/base';
import { deserialize } from '../../cocos/serialization/deserialize';

import { generateSpriteGeometry, MAX_SPRITE_QUADS } from '../../cocos/2d/utils/sprite-renderer-geometry';
// Object/geometry regressions using Empty GFX. Actual Web/Native rendering is verified separately.
describe('SpriteRenderer sliced and tiled', () => {
    let scene: Scene;
    let frames: SpriteFrame[];
    let textures: Texture2D[];
    let materials: Material[];

    beforeAll(() => {
        // Generated by the Cocos Effect compiler from builtin-sprite-renderer.effect and current engine chunks.
        // This exercises real reflected material parameters, not GPU output.
        const effect = Object.assign(new EffectAsset(), require('../fixtures/sprite-renderer-effect.json'));
        effect.onLoaded();
    });

    function material (): Material {
        const result = new Material();
        result.initialize({ effectName: 'builtin-sprite-renderer' });
        materials.push(result);
        return result;
    }

    function texture (size = 256): Texture2D {
        const result = new Texture2D();
        result.reset({ width: size, height: size });
        textures.push(result);
        return result;
    }

    function frame (): SpriteFrame {
        const result = new SpriteFrame();
        result.texture = texture();
        result.rect = new Rect(16, 32, 100, 60);
        frames.push(result);
        return result;
    }

    function renderer (active = true): SpriteRenderer {
        const node = new Node('World sprite');
        node.active = active;
        scene.addChild(node);
        return node.addComponent(SpriteRenderer);
    }

    beforeEach(() => {
        frames = [];
        textures = [];
        materials = [];
        scene = new Scene('SpriteRenderer regression');
        director.runSceneImmediate(scene);
    });

    afterEach(() => {
        scene.destroy();
        CCObject._deferredDestroy();
        frames.forEach((asset) => { if (isValid(asset, true)) asset.destroy(); });
        textures.forEach((asset) => { if (isValid(asset, true)) asset.destroy(); });
        materials.forEach((asset) => { if (isValid(asset, true)) asset.destroy(); });
        CCObject._deferredDestroy();
        jest.restoreAllMocks();
    });

    function sliced (asset = frame()): SpriteRenderer {
        const c = renderer();
        c.drawMode = SpriteDrawMode.SLICED;
        c.size = new Vec2(2, 1);
        c.setSharedMaterial(material(), 0);
        c.spriteFrame = asset;
        return c;
    }
    function mesh (c: SpriteRenderer) { return (c as any)._boundMesh; }
    function geometry (f: SpriteFrame, x: number, y: number, mode = SpriteDrawMode.TILED, tileMode = SpriteTileMode.CONTINUOUS, threshold = 0.5) {
        return generateSpriteGeometry(f, x, y, mode, tileMode, threshold);
    }

    test('all draw modes preserve explicit source corners, including the fourth corner', () => {
        const asset = frame();
        asset.insetLeft = asset.insetRight = asset.insetTop = asset.insetBottom = 0;
        asset.uv.splice(0, 8, 0.5, 1, 1, 1, 0.5, 0, 0.75, 0.25);
        const expected = [0.5, 0, 1, 0, 0.5, 1, 0.75, 0.75];
        const sprite = renderer();
        sprite.spriteFrame = asset;
        for (const mode of [SpriteDrawMode.SIMPLE, SpriteDrawMode.SLICED, SpriteDrawMode.TILED]) {
            sprite.drawMode = mode;
            expect(Array.from(mesh(sprite).readAttribute(0, AttributeName.ATTR_TEX_COORD))).toEqual(expected);
        }
    });

    test('prewarming before a Pivot edit gives every renderer the same bounds as a fresh frame', () => {
        const asset = frame();
        asset.ensureMeshData();
        const old = asset.mesh!;
        old.addRef();
        try {
            asset.pivot.set(0, 0);
            const fresh = asset.clone();
            frames.push(fresh);
            const reference = renderer();
            reference.spriteFrame = fresh;
            const referenceBounds = reference.model!.modelBounds!;
            for (const mode of [SpriteDrawMode.SIMPLE, SpriteDrawMode.SLICED, SpriteDrawMode.TILED]) {
                const sprite = renderer();
                sprite.drawMode = mode;
                sprite.spriteFrame = asset;
                expect(sprite.model!.modelBounds!.center).toEqual(referenceBounds.center);
                expect(sprite.model!.modelBounds!.halfExtents).toEqual(referenceBounds.halfExtents);
            }
            expect(asset.mesh).not.toBe(old);
            expect(isValid(old, true)).toBe(true);
            expect(old.struct.minPosition!.x).toBeLessThan(0);
            expect(asset.mesh!.struct.minPosition!.x).toBe(0);
        } finally {
            old.decRef();
        }
    });

    test('re-enabling a sized consumer refreshes shared and owned geometry after an in-place Pivot edit', () => {
        const asset = frame(), sized = sliced(asset), simple = renderer();
        simple.spriteFrame = asset;
        const oldShared = asset.mesh, oldSized = mesh(sized);
        sized.enabled = false;
        asset.pivot.set(1, 0);
        sized.enabled = true;
        expect(asset.mesh).not.toBe(oldShared);
        expect(mesh(sized)).not.toBe(oldSized);
        for (const sprite of [simple, sized]) {
            const bounds = sprite.model!.modelBounds!;
            expect(bounds.center.x + bounds.halfExtents.x).toBeCloseTo(0);
            expect(bounds.center.y - bounds.halfExtents.y).toBeCloseTo(0);
        }
    });

    test('a source replaced by a geometry-change listener is checked before building the model', () => {
        const asset = frame(), sprite = sliced(asset);
        const late = new Texture2D();
        textures.push(late);
        sprite.enabled = false;
        asset.pivot.set(0, 0);
        asset.once(SpriteFrameEvent.MESH_CHANGED, () => { asset.texture = late; });
        sprite.enabled = true;
        expect(sprite.model).toBeNull();
        late.reset({ width: 64, height: 64 });
        expect(asset.texture).toBe(late);
        expect(sprite.model).not.toBeNull();
    });

    test.each([false, true])('a border-only reset preserves source UVs and rebuilds sized meshes once (packed=%s)', (packed) => {
        const asset = frame(), simple = renderer(), nine = renderer(), tiled = renderer();
        asset.uv.splice(0, 8, 0.5, 1, 1, 1, 0.5, 0, 1, 0);
        if (packed) asset._setDynamicAtlasFrame({ texture: texture(1024), x: 300, y: 400 });
        nine.drawMode = SpriteDrawMode.SLICED; tiled.drawMode = SpriteDrawMode.TILED;
        simple.spriteFrame = nine.spriteFrame = tiled.spriteFrame = asset;
        const shared = asset.mesh, oldNine = mesh(nine), oldTiled = mesh(tiled);
        const changed = jest.fn(), border = jest.fn(), uv = jest.fn();
        asset.on(SpriteFrameEvent.MESH_CHANGED, changed);
        asset.on(SpriteFrameEvent.BORDER_CHANGED, border);
        asset.on(SpriteFrameEvent.UV_UPDATED, uv);
        asset.reset({ borderLeft: 8, borderRight: 9, borderBottom: 2 });
        expect(changed).not.toHaveBeenCalled();
        expect(border).toHaveBeenCalledTimes(1);
        expect(uv).toHaveBeenCalledTimes(1);
        expect(asset.mesh).toBe(shared);
        expect(mesh(nine)).not.toBe(oldNine);
        expect(mesh(tiled)).not.toBe(oldTiled);
        for (const sprite of [simple, nine, tiled]) {
            expect(mesh(sprite).readAttribute(0, AttributeName.ATTR_TEX_COORD)[0]).toBe(0.5);
        }
        const installed = mesh(nine);
        asset.reset({ borderLeft: 8 });
        expect(mesh(nine)).toBe(installed);
        asset.reset({ rect: new Rect(asset.rect.x + 8, asset.rect.y, 32, 32), borderLeft: 4 });
        expect(changed).toHaveBeenCalledTimes(1);
        expect(mesh(nine).readAttribute(0, AttributeName.ATTR_TEX_COORD)[0]).toBeCloseTo(24 / 256);
    });

    test('resubmitting a directly edited Rect refreshes automatic corners', () => {
        const asset = frame(), sprite = renderer();
        sprite.spriteFrame = asset;
        asset.rect.x += 16;
        asset.reset({ rect: asset.rect });
        expect(asset.uv[0]).toBeCloseTo(32 / 256);
        expect(asset.mesh!.readAttribute(0, AttributeName.ATTR_TEX_COORD)![0]).toBeCloseTo(32 / 256);
    });

    test('legacy mode/size stay inactive, while new explicit zero survives deserialization', () => {
        const old = deserialize({ __type__: 'cc.SpriteRenderer', _mode: 2, _size: { __type__: 'cc.Vec2', x: 3, y: 2 } }) as SpriteRenderer;
        expect(old.drawMode).toBe(SpriteDrawMode.SIMPLE);
        expect(old.size).toEqual(new Vec2(1, 1));
        const current = deserialize({ __type__: 'cc.SpriteRenderer', _drawMode: 2, _renderSize: { __type__: 'cc.Vec2', x: 0, y: 2 } }) as SpriteRenderer;
        expect(current.drawMode).toBe(SpriteDrawMode.TILED);
        expect(current.size).toEqual(new Vec2(0, 2));
    });

    test('uses natural size only until an explicit size is assigned', () => {
        const c = renderer(); c.drawMode = SpriteDrawMode.SLICED; c.spriteFrame = frame();
        expect(c.size).toEqual(new Vec2(1, 0.6));
        c.size = new Vec2(0, 1); c.onRestore();
        expect(c.model).toBeNull();
        c.size = new Vec2(2, 1); expect(c.model).not.toBeNull();
    });

    test.each([SpriteDrawMode.SLICED, SpriteDrawMode.TILED])(
        'mode %s follows the current frame size until an explicit size is assigned', (mode) => {
            const first = frame();
            const second = frame();
            second.rect = new Rect(0, 0, 200, 40);
            const component = renderer();
            component.drawMode = mode;

            function expectSize (width: number, height: number): void {
                expect(component.size).toEqual(new Vec2(width, height));
                const { halfExtents } = component.model!.modelBounds!;
                expect(2 * halfExtents.x).toBeCloseTo(width);
                expect(2 * halfExtents.y).toBeCloseTo(height);
            }

            component.spriteFrame = first;
            expectSize(1, 0.6);
            component.spriteFrame = second;
            expectSize(2, 0.4);

            // Assigning even the current natural dimensions makes the target size explicit.
            component.size = new Vec2(2, 0.4);
            component.spriteFrame = first;
            expectSize(2, 0.4);
        },
    );

    test.each([SpriteDrawMode.SLICED, SpriteDrawMode.TILED])(
        'the shared Simple mesh is retained until the last mode %s consumer detaches', (mode) => {
            const asset = frame();
            const textureRefsBefore = asset.texture.refCount;
            const simple = renderer();
            simple.spriteFrame = asset;
            const shared = asset.mesh!;
            const sized = renderer();
            sized.drawMode = mode;
            sized.spriteFrame = asset;
            const ownedSubMesh = sized.model!.subModels[0].subMesh;
            expect(ownedSubMesh).not.toBe(shared.renderingSubMeshes[0]);

            simple.spriteFrame = null;
            expect(asset.mesh).toBe(shared);
            expect(isValid(shared, true)).toBe(true);
            expect(sized.model!.subModels[0].subMesh).toBe(ownedSubMesh);

            sized.spriteFrame = null;
            expect(asset.mesh).toBeNull();
            expect(isValid(shared, true)).toBe(false);
            expect(asset.texture.refCount).toBe(textureRefsBefore);
        },
    );

    test('owns independent geometry and leaves Simple and UI source data unchanged', () => {
        const f = frame(); f.insetLeft = f.insetRight = 10; f.insetTop = f.insetBottom = 10;
        const a = sliced(f), b = sliced(f), simple = renderer(); simple.spriteFrame = f;
        expect(mesh(a)).not.toBe(mesh(b)); expect(mesh(a)).not.toBe(f.mesh);
        const shared = f.mesh, other = mesh(b);
        a.size = new Vec2(4, 3);
        expect(f.mesh).toBe(shared); expect(mesh(b)).toBe(other); expect(f.vertices).toBeNull();
        const data = Array.from(mesh(a).readAttribute(0, AttributeName.ATTR_POSITION)) as number[];
        expect(data[0]).toBe(-2); expect(data[3]).toBeCloseTo(-1.9);
        expect(mesh(a).struct.primitives[0].indexView.count).toBe(54);
        expect(a.model!.modelBounds!.halfExtents.x).toBe(2);
    });

    test('compresses borders and omits the collapsed center', () => {
        const f = frame(); f.insetLeft = f.insetRight = 20;
        const g = geometry(f, 0.3, 0.6, SpriteDrawMode.SLICED).geometry!;
        expect(g.indices!.length).toBe(12);
        expect(g.positions[3]).toBeCloseTo(0);
        expect(g.positions[12]).toBeCloseTo(0);
    });

    test('non-finite and zero size transitions clear the model and recover on valid input', () => {
        const c = sliced();
        c.size = new Vec2(Infinity, 1);
        expect(c.size.x).toBe(Infinity);
        expect(c.model).toBeNull();
        c.size = new Vec2(2, 1);
        expect(c.model!.modelBounds!.halfExtents.x).toBe(1);
        const invalid = new Vec2(2, 1);
        invalid.x = NaN;
        c.size = invalid;
        expect(c.size.x).toBeNaN();
        expect(c.model).toBeNull();
        c.size = new Vec2(5e-7, 1);
        expect(c.model).not.toBeNull();
        c.size = new Vec2(0, 1);
        expect(c.size.x).toBe(0);
        expect(c.model).toBeNull();
        c.size = new Vec2(5e-7, 1);
        expect(c.model).not.toBeNull();
    });

    test('editing a size snapshot only affects the mesh when assigned', () => {
        const c = sliced();
        const next = c.size.set(4, 1);
        expect(c.size.x).toBe(2);
        c.size = next;
        expect(c.model!.modelBounds!.halfExtents.x).toBe(2);
    });

    test('Continuous resizes independently of an invalid Adaptive threshold', () => {
        const c = sliced();
        c.drawMode = SpriteDrawMode.TILED;
        c.adaptiveModeThreshold = 2;
        c.size = new Vec2(3, 1);
        expect(c.model!.modelBounds!.halfExtents.x).toBe(1.5);
        c.tileMode = SpriteTileMode.ADAPTIVE;
        expect(c.model).toBeNull();
        c.tileMode = SpriteTileMode.CONTINUOUS;
        expect(c.model!.modelBounds!.halfExtents.x).toBe(1.5);
    });

    test('a collapsed axis cannot hide an oversized repeat count on the other axis', () => {
        const f = frame();
        f.rect = new Rect(0, 0, 100, 100);
        f.insetTop = f.insetBottom = 50;
        expect(geometry(f, MAX_SPRITE_QUADS + 1, Number.MIN_VALUE).geometry).toBeNull();
        expect(geometry(f, 1, Number.MIN_VALUE).geometry).toBeNull();
    });

    test('Continuous clips the final tile in geometry and UVs', () => {
        const f = frame(); const g = geometry(f, 2.5, 0.6).geometry!;
        expect(g.indices!.length).toBe(18);
        expect(g.positions[27] - g.positions[24]).toBeCloseTo(0.5);
        expect(g.uvs![18] - g.uvs![16]).toBeCloseTo(50 / 256);
        expect(g.maxPos!.x).toBeCloseTo(1.25);
    });

    test.each([[1.49, 0.5, 1], [1.5, 0.5, 2], [1.51, 0.5, 2], [2, 0.5, 2], [2.5, 0.5, 3], [1.01, 0, 2], [1.99, 1, 1], [2, 1, 2]])(
        'Adaptive ratio %s threshold %s uses %s complete tiles', (size, threshold, count) => {
            const f = frame(); const g = geometry(f, size, 0.6, SpriteDrawMode.TILED, SpriteTileMode.ADAPTIVE, threshold).geometry!;
            expect(g.indices!.length).toBe(count * 6);
            for (let i = 0; i < count; i++) expect(g.uvs!.slice(i * 8, i * 8 + 8)).toEqual(f._getSourceUVs());
        },
    );

    test.each([[-1, 1], [Infinity, 1], [NaN, 1], [1, -1], [1, Infinity]])('rejects size %s/%s', (x, y) => {
        expect(geometry(frame(), x, y).error).toBeDefined();
    });
    test('rejects invalid borders, zero repeat units and excessive geometry before allocation', () => {
        const f = frame(); f.insetLeft = 101;
        expect(geometry(f, 2, 1).error).toBe('invalid source border');
        f.insetLeft = 100;
        expect(geometry(f, 2, 1).error).toMatch('positive source repeat size');
        f.insetLeft = 0;
        expect(geometry(f, MAX_SPRITE_QUADS + 1, 0.6).error).toMatch('exceeds');
        expect(geometry(f, 1e300, 1e300).error).toMatch('exceeds');
        expect(geometry(f, 1, 1, SpriteDrawMode.TILED, SpriteTileMode.ADAPTIVE, NaN).error).toBeDefined();
    });
    test('accepts the exact 16-bit-safe limit and exact tile multiples without extra slivers', () => {
        const f = frame();
        expect(geometry(f, MAX_SPRITE_QUADS, 0.6).geometry!.positions.length).toBe(MAX_SPRITE_QUADS * 12);
        expect(geometry(f, 3, 1.8).geometry!.indices!.length).toBe(54);
    });
    test('rejects finite PPU values whose derived local dimensions overflow', () => {
        const f = frame();
        (f as any)._pixelsToUnit = Number.MIN_VALUE;
        expect(geometry(f, 2, 1).error).toMatch('overflow');
        f.insetLeft = 10;
        expect(geometry(f, 2, 1, SpriteDrawMode.SLICED).error).toMatch('overflow');
    });

    test.each([false, true])('supports source UV flips and static rotation (%s) without repeating the atlas', rotated => {
        const f = frame(); f.rotated = rotated;
        for (const [x, y] of [[false, false], [true, false], [false, true], [true, true]]) {
            f.flipUVX = x; f.flipUVY = y;
            const g = geometry(f, 2, 1.2).geometry!;
            for (let i = 0; i < 4; i++) expect(g.uvs!.slice(i * 8, i * 8 + 8)).toEqual(f._getSourceUVs());
            const before = g.uvs;
            f._setDynamicAtlasFrame({ texture: texture(1024), x: 400, y: 500 });
            expect(geometry(f, 2, 1.2).geometry!.uvs).toEqual(before);
            f._resetDynamicAtlasFrame();
        }
    });

    test('border changes rebuild only sized geometry, with old buffers detached first', () => {
        const f = frame(), c = sliced(f), simple = renderer(); simple.spriteFrame = f;
        const old = mesh(c), shared = f.mesh, sub = old.renderingSubMeshes[0];
        const original = sub.destroy.bind(sub);
        jest.spyOn(sub, 'destroy').mockImplementation(() => { expect(c.model).toBeNull(); original(); });
        f.insetLeft = 10;
        expect(isValid(old, true)).toBe(false); expect(f.mesh).toBe(shared);
        expect(mesh(c).struct.primitives[0].indexView.count).toBe(12);
    });
    test('UI packing preserves owned mesh and retains source texture until clear', () => {
        const f = frame(), source = f.texture, initial = source.refCount, c = sliced(f);
        const m = mesh(c), model = c.model;
        expect(f.mesh).toBeNull(); expect(source.refCount).toBe(initial + 1);
        f._setDynamicAtlasFrame({ texture: texture(1024), x: 400, y: 500 });
        f._resetDynamicAtlasFrame();
        expect(mesh(c)).toBe(m); expect(c.model).toBe(model);
        c.spriteFrame = null;
        expect(isValid(m, true)).toBe(false); expect(source.refCount).toBe(initial);
    });
    test('inactive edits defer allocations and invalid inputs stop stale submission', () => {
        const c = sliced(), old = mesh(c);
        c.enabled = false; c.size = new Vec2(3, 2);
        expect(c.model).toBeNull(); expect(isValid(old, true)).toBe(false); expect(mesh(c)).toBeNull();
        c.enabled = true; expect(c.model!.modelBounds!.halfExtents.x).toBe(1.5);
        c.size = new Vec2(-1, 2); expect(c.model).toBeNull();
        c.size = new Vec2(2, 1); expect(c.model).not.toBeNull();
        c.enabled = false; c.spriteFrame!.insetLeft = 20;
        expect(c.model).toBeNull(); c.enabled = true; expect(c.model).not.toBeNull();
    });
    test('mode switches preserve tint/flip/bounds, and destroy owns no borrowed resources', () => {
        const c = sliced(), f = c.spriteFrame!, source = f.texture;
        c.color = Color.RED; c.flipX = true; c.priority = 420; c.visibility = 4;
        for (let i = 0; i < 20; i++) {
            const own = mesh(c); c.drawMode = SpriteDrawMode.SIMPLE;
            expect(isValid(own, true)).toBe(false); expect(mesh(c)).toBe(f.mesh);
            c.drawMode = SpriteDrawMode.TILED;
            expect(c.model!.priority).toBe(420); expect(c.model!.visFlags).toBe(4);
            expect(c.getRenderMaterial(0)!.getProperty('spriteColor')).toEqual(Color.RED);
        }
        const own = mesh(c); f.destroy();
        expect(c.model).toBeNull(); expect(isValid(own, true)).toBe(false); expect(source.refCount).toBe(0);
    });
});
